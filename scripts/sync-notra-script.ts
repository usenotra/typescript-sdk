// Pins the builds the ingest currently serves as /api/notra.js and
// /api/notra.plus.js: reads each one's version from its ETag, downloads the
// immutable /api/notra.<version>.js and rewrites src/script/releases.ts.
// Usage: bun run sync-script [origin], origin defaults to the Notra ingest.
import { createHash } from "node:crypto";
import { writeFile } from "node:fs/promises";

import { DEFAULT_ENDPOINT } from "../src/tracking/constants.js";
import {
  SCRIPT_FILE,
  SCRIPT_PATH,
  SCRIPT_PLUS_FILE,
} from "../src/tracking/script/constants.js";
import type { NotraScriptRelease } from "../src/tracking/script/types.js";

const VERSION_PATTERN = /^[0-9a-f]{12}$/;
const RELEASES_FILE = new URL("../src/tracking/script/releases.ts", import.meta.url);

const origin = (process.argv[2] ?? DEFAULT_ENDPOINT).replace(/\/+$/, "");

async function pin(latest: string): Promise<NotraScriptRelease> {
  const current = await fetch(`${origin}${SCRIPT_PATH}${latest}`);
  await current.body?.cancel();
  if (!current.ok) {
    throw new Error(`${latest}: HTTP ${current.status}`);
  }
  const version = current.headers
    .get("etag")
    ?.replace(/^W\//, "")
    .replaceAll('"', "");
  if (!(version && VERSION_PATTERN.test(version))) {
    throw new Error(`${latest}: expected a 12 hex character ETag`);
  }

  const file = latest.replace(/\.js$/, `.${version}.js`);
  const response = await fetch(`${origin}${SCRIPT_PATH}${file}`);
  if (!response.ok) {
    throw new Error(`${file}: HTTP ${response.status}`);
  }
  const body = new Uint8Array(await response.arrayBuffer());
  // The version is the start of the build's sha256, so this catches a body
  // that changed on the way.
  const sha256 = createHash("sha256").update(body).digest("hex");
  if (!sha256.startsWith(version)) {
    throw new Error(`${file}: body does not match version ${version}`);
  }
  const sha384 = createHash("sha384").update(body).digest("base64");
  return { file, integrity: `sha384-${sha384}` };
}

function constant(name: string, release: NotraScriptRelease): string {
  return `export const ${name}: NotraScriptRelease = {
  file: ${JSON.stringify(release.file)},
  integrity:
    ${JSON.stringify(release.integrity)},
};
`;
}

const [release, plusRelease] = await Promise.all([
  pin(SCRIPT_FILE),
  pin(SCRIPT_PLUS_FILE),
]);

await writeFile(
  RELEASES_FILE,
  `// Generated by \`bun run sync-script\`. Do not edit.
import type { NotraScriptRelease } from "./types";

${constant("NOTRA_SCRIPT_RELEASE", release)}
${constant("NOTRA_SCRIPT_PLUS_RELEASE", plusRelease)}`
);

console.log(`Pinned ${release.file} and ${plusRelease.file}`);
