// Generates the typed API client from spec/openapi.json:
//   src/generated/schema.ts  every request and response type (openapi-typescript)
//   src/generated/api.ts     one class per API group, one method per operationId
//   docs/API.md              the method reference
// Usage: bun run generate. A test fails when the output is stale.
import openapiTS, { astToString } from "openapi-typescript";

const root = new URL("..", import.meta.url);
export const SPEC_FILE = new URL("spec/openapi.json", root);
export const SCHEMA_FILE = new URL("src/generated/schema.ts", root);
export const API_FILE = new URL("src/generated/api.ts", root);
export const REFERENCE_FILE = new URL("docs/API.md", root);

const HEADER = "// Generated by `bun run generate` from spec/openapi.json. Do not edit.\n";
const METHODS = ["get", "post", "put", "patch", "delete"] as const;

interface Parameter {
  name: string;
  in: "path" | "query" | "header" | "cookie";
  required?: boolean;
}

interface Operation {
  operationId: string;
  tags?: string[];
  summary?: string;
  description?: string;
  deprecated?: boolean;
  parameters?: Parameter[];
  requestBody?: { required?: boolean; content?: Record<string, unknown> };
  responses: Record<string, { content?: Record<string, unknown> }>;
}

interface Spec {
  info: { title: string; version: string };
  paths: Record<string, Partial<Record<(typeof METHODS)[number], Operation>> & { parameters?: Parameter[] }>;
}

export interface Endpoint {
  group: string;
  id: string;
  method: Uppercase<(typeof METHODS)[number]>;
  path: string;
  summary: string;
  description: string | undefined;
  deprecated: boolean;
  pathParams: string[];
  queryParams: string[];
  queryRequired: boolean;
  body: "none" | "required" | "optional";
  status: string;
  response: "json" | "sse" | "ndjson";
}

/** Every operation, grouped by its tag, in spec order. */
export function endpoints(spec: Spec): Endpoint[] {
  const result: Endpoint[] = [];
  const seen = new Set<string>();
  for (const [path, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const operation = item[method];
      if (!operation) {
        continue;
      }
      const id = operation.operationId;
      const tag = operation.tags?.[0];
      if (!(id && tag)) {
        throw new Error(`${method.toUpperCase()} ${path} needs an operationId and a tag`);
      }
      if (seen.has(id)) {
        throw new Error(`Duplicate operationId ${id}`);
      }
      seen.add(id);
      const parameters = [...(item.parameters ?? []), ...(operation.parameters ?? [])];
      const pathParams = parameters.filter((p) => p.in === "path").map((p) => p.name);
      const query = parameters.filter((p) => p.in === "query");
      const names = [...pathParams, ...query.map((p) => p.name)];
      if (names.includes("body") || new Set(names).size !== names.length) {
        throw new Error(`${id}: parameter names must be unique and not "body"`);
      }
      const [status, success] = Object.entries(operation.responses).find(([code]) => code.startsWith("2")) ?? [];
      if (!(status && success)) {
        throw new Error(`${id} has no 2xx response`);
      }
      const types = Object.keys(success.content ?? {});
      const response = types.includes("text/event-stream") ? "sse" : types.includes("application/x-ndjson") ? "ndjson" : "json";
      const bodyContent = operation.requestBody?.content;
      if (bodyContent && !("application/json" in bodyContent)) {
        throw new Error(`${id}: only JSON request bodies are supported`);
      }
      result.push({
        group: tag,
        id,
        method: method.toUpperCase() as Endpoint["method"],
        path,
        summary: operation.summary ?? id,
        description: operation.description,
        deprecated: operation.deprecated === true,
        pathParams,
        queryParams: query.map((p) => p.name),
        queryRequired: query.some((p) => p.required),
        body: bodyContent ? (operation.requestBody?.required ? "required" : "optional") : "none",
        status,
        response,
      });
    }
  }
  return result;
}

/** `Event Triggers` → `eventTriggers`, `GEO` → `geo`. */
export function groupProperty(tag: string): string {
  const words = tag.split(/[^A-Za-z0-9]+/).filter(Boolean);
  return words.map((word, index) => (index === 0 ? word.toLowerCase() : word[0]!.toUpperCase() + word.slice(1).toLowerCase())).join("");
}

function byGroup(list: Endpoint[]): Map<string, Endpoint[]> {
  const groups = new Map<string, Endpoint[]>();
  for (const endpoint of list) {
    groups.set(endpoint.group, [...(groups.get(endpoint.group) ?? []), endpoint]);
  }
  return groups;
}

function pascal(value: string): string {
  return value[0]!.toUpperCase() + value.slice(1);
}

function groupClass(tag: string): string {
  return `${pascal(groupProperty(tag))}Resource`;
}

function hasParams(endpoint: Endpoint): boolean {
  return endpoint.pathParams.length > 0 || endpoint.queryParams.length > 0 || endpoint.body !== "none";
}

function paramsOptional(endpoint: Endpoint): boolean {
  return endpoint.pathParams.length === 0 && !endpoint.queryRequired && endpoint.body !== "required";
}

function paramsType(endpoint: Endpoint): string {
  const op = `operations["${endpoint.id}"]`;
  const parts: string[] = [];
  if (endpoint.pathParams.length > 0) {
    parts.push(`${op}["parameters"]["path"]`);
  }
  if (endpoint.queryParams.length > 0) {
    parts.push(endpoint.queryRequired ? `${op}["parameters"]["query"]` : `NonNullable<${op}["parameters"]["query"]>`);
  }
  if (endpoint.body === "required") {
    parts.push(`{ body: ${op}["requestBody"]["content"]["application/json"] }`);
  } else if (endpoint.body === "optional") {
    parts.push(`{ body?: NonNullable<${op}["requestBody"]>["content"]["application/json"] }`);
  }
  return `Prettify<${parts.join(" & ")}>`;
}

function resultType(endpoint: Endpoint): string {
  if (endpoint.response === "sse") {
    return "NotraStream<NotraChatChunk>";
  }
  if (endpoint.response === "ndjson") {
    return "NotraStream<NotraAgentEvent>";
  }
  return `operations["${endpoint.id}"]["responses"][${endpoint.status}]["content"]["application/json"]`;
}

function doc(lines: Array<string | undefined>, indent: string): string {
  const text = lines
    .filter((line): line is string => line !== undefined)
    .join("\n\n")
    .replaceAll("*/", "*\\/")
    .split("\n")
    .map((line) => `${indent} *${line ? ` ${line}` : ""}`);
  return `${indent}/**\n${text.join("\n")}\n${indent} */\n`;
}

export function renderApi(list: Endpoint[]): string {
  const groups = byGroup(list);
  let out = HEADER;
  out += 'import type { Transport } from "../client/transport.js";\n';
  out += 'import type { NotraStream } from "../client/stream.js";\n';
  out += 'import type { NotraAgentEvent, NotraChatChunk, OperationSpec, Prettify, RequestOptions } from "../client/types.js";\n';
  out += 'import type { operations } from "./schema.js";\n\n';

  for (const endpoint of list) {
    const type = pascal(endpoint.id);
    if (hasParams(endpoint)) {
      out += `/** Parameters of \`${groupProperty(endpoint.group)}.${endpoint.id}()\`. */\n`;
      out += `export type ${type}Params = ${paramsType(endpoint)};\n`;
    }
    out += `/** What \`${groupProperty(endpoint.group)}.${endpoint.id}()\` resolves to. */\n`;
    out += `export type ${type}Result = ${resultType(endpoint)};\n\n`;
  }

  out += "const OPERATIONS = {\n";
  for (const endpoint of list) {
    const spec = {
      method: endpoint.method,
      path: endpoint.path,
      pathParams: endpoint.pathParams,
      queryParams: endpoint.queryParams,
      body: endpoint.body !== "none",
      response: endpoint.response,
    };
    out += `  ${endpoint.id}: ${JSON.stringify(spec)},\n`;
  }
  out += "} satisfies Record<string, OperationSpec>;\n\n";

  for (const [tag, members] of groups) {
    out += doc([`The ${tag} endpoints, as \`notra.${groupProperty(tag)}\`.`], "");
    out += `export class ${groupClass(tag)} {\n  readonly #transport: Transport;\n\n  constructor(transport: Transport) {\n    this.#transport = transport;\n  }\n`;
    for (const endpoint of members) {
      const type = pascal(endpoint.id);
      out += "\n";
      out += doc([endpoint.summary, endpoint.description, `\`${endpoint.method} ${endpoint.path}\``, endpoint.deprecated ? "@deprecated" : undefined], "  ");
      const args = hasParams(endpoint) ? `params${paramsOptional(endpoint) ? "?" : ""}: ${type}Params, options?: RequestOptions` : "options?: RequestOptions";
      const passed = hasParams(endpoint) ? "params" : "undefined";
      out += `  ${endpoint.id}(${args}): Promise<${type}Result> {\n`;
      out += `    return this.#transport.call(OPERATIONS.${endpoint.id}, ${passed}, options) as Promise<${type}Result>;\n  }\n`;
    }
    out += "}\n\n";
  }

  out += "/** Every API group, as properties of `Notra`. */\nexport class NotraApi {\n";
  for (const tag of groups.keys()) {
    out += `  readonly ${groupProperty(tag)}: ${groupClass(tag)};\n`;
  }
  out += "  /** The transport every group shares; `Notra.request()` uses it too. */\n  protected readonly transport: Transport;\n";
  out += "\n  constructor(transport: Transport) {\n    this.transport = transport;\n";
  for (const tag of groups.keys()) {
    out += `    this.${groupProperty(tag)} = new ${groupClass(tag)}(transport);\n`;
  }
  out += "  }\n}\n";
  return out;
}

export function renderReference(list: Endpoint[], spec: Spec): string {
  const groups = byGroup(list);
  let out = "<!-- Generated by `bun run generate` from spec/openapi.json. Do not edit. -->\n\n";
  out += `# API reference\n\nEvery method of \`new Notra()\`, generated from the ${spec.info.title} OpenAPI spec. Each method takes its parameters as one object (path and query parameters by name, the JSON body as \`body\`) and an optional \`RequestOptions\` (\`signal\`, \`timeoutMs\`, \`maxRetries\`, \`headers\`). \`<Method>Result\` is exported for every method, and \`<Method>Params\` for every method that takes parameters.\n\n`;
  for (const [tag] of groups) {
    out += `- [${tag}](#${tag.toLowerCase().replaceAll(/[^a-z0-9]+/g, "-")}) (\`notra.${groupProperty(tag)}\`)\n`;
  }
  for (const [tag, members] of groups) {
    out += `\n## ${tag}\n\n| Method | Endpoint | Summary |\n| --- | --- | --- |\n`;
    for (const endpoint of members) {
      const call = `notra.${groupProperty(tag)}.${endpoint.id}()`;
      const streaming = endpoint.response === "json" ? "" : " (stream)";
      const summary = `${endpoint.deprecated ? "**Deprecated.** " : ""}${endpoint.summary}${streaming}`.replaceAll("|", "\\|");
      out += `| \`${call}\` | \`${endpoint.method} ${endpoint.path}\` | ${summary} |\n`;
    }
  }
  return out;
}

export async function generate(spec: Spec): Promise<{ schema: string; api: string; reference: string }> {
  const ast = await openapiTS(spec as never, { rootTypes: true, rootTypesNoSchemaPrefix: true });
  const list = endpoints(spec);
  return { schema: HEADER + astToString(ast), api: renderApi(list), reference: renderReference(list, spec) };
}

if (import.meta.main) {
  const spec = (await Bun.file(SPEC_FILE).json()) as Spec;
  const { schema, api, reference } = await generate(spec);
  await Bun.write(SCHEMA_FILE, schema);
  await Bun.write(API_FILE, api);
  await Bun.write(REFERENCE_FILE, reference);
  console.log(`Generated ${endpoints(spec).length} operations`);
}
